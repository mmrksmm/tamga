# ---------- сборка предложений из базы фрагментов ----------
TOK = re.compile(r"[^\s.,!?;:«»\"“”()…]+")
def words(t): return TOK.findall(t)

def build_task(s, exclude=()):
    pool = [(f, a) for f, a in s.query(Fragment, AutoTr).join(AutoTr, AutoTr.fragment_id == Fragment.id)
            .filter(AutoTr.pair == "ba-ru", Fragment.active == True).all()  # noqa: E712
            if 3 <= len(words(f.text_ba)) <= 7 and f.id not in exclude and "(" not in f.text_ba and "..." not in f.text_ba]
    if not pool: return None
    f, a = random.choice(pool)
    w = words(f.text_ba)
    others = [x for (t,) in s.query(Fragment.text_ba).limit(400) for x in words(t) if x.lower() not in {y.lower() for y in w}]
    extra = random.sample(others, min(2, len(others)))          # лишние слова — «подковырка»
    tiles = w + extra
    while len(tiles) > 1 and tiles[:len(w)] == w: random.shuffle(tiles)
    return {"kind": "build", "id": f.id, "ru": a.text, "tiles": tiles, "count": len(w)}

class QuizIn(BaseModel): id: int; choice: int
class BuildIn(BaseModel): id: int; words: list[str] = Field(max_length=20)

XP_DAY_CAP = 50   # XP за обучение в день — не больше, чтобы не «фармили»

def give_xp(s, u, n):
    today = dt.date.today()
    got = sum(int(a.detail or 0) for a in s.query(Audit).filter(Audit.user_id == u.id, Audit.action == "learn_xp", Audit.created_at >= dt.datetime.combine(today, dt.time())))
    n = max(0, min(n, XP_DAY_CAP - got))
    if n: u.xp += n; s.add(Audit(user_id=u.id, action="learn_xp", detail=str(n)))
    return n

@router.get("/facts")
def facts(u: User = Depends(current_user)):
    day = dt.date.today().toordinal()
    out = [{"id": k, "icon": i, "title": t, "text": x} for k, i, t, x in FACTS]
    return {"fact_of_day": out[day % len(out)], "facts": out}

@router.get("/quiz")
def quiz(u: User = Depends(current_user)):
    return [quiz_q(i) for i in random.sample(range(len(QUIZ)), 5)]

@router.post("/quiz/check")
def quiz_check(d: QuizIn, u: User = Depends(current_user), s: Session = Depends(db)):
    limiter.hit(f"learn:{u.id}", 60, 60)
    if not 0 <= d.id < len(QUIZ): raise HTTPException(404, "Вопрос не найден")
    _, opts, right, why = QUIZ[d.id]
    ok = d.choice == right
    xp = give_xp(s, u, 2) if ok else 0; s.commit()
    return {"correct": ok, "right": right, "explain": why, "xp": xp}

@router.get("/build")
def build(u: User = Depends(current_user), s: Session = Depends(db)):
    t = build_task(s)
    if not t: raise HTTPException(404, "Пока нет подходящих предложений")
    return t

@router.post("/build/check")
def build_check(d: BuildIn, u: User = Depends(current_user), s: Session = Depends(db)):
    limiter.hit(f"learn:{u.id}", 60, 60)
    f = s.get(Fragment, d.id)
    if not f: raise HTTPException(404, "Предложение не найдено")
    ok = [x.lower() for x in d.words] == [x.lower() for x in words(f.text_ba)]
    xp = give_xp(s, u, 3) if ok else 0; s.commit()
    return {"correct": ok, "answer": f.text_ba, "xp": xp}

@router.get("/test")
def test(u: User = Depends(current_user), s: Session = Depends(db)):
    """Контрольная: 6 вопросов с подвохом + 4 предложения на сборку."""
    items = [quiz_q(i) for i in random.sample(range(len(QUIZ)), 6)]
    used = set()
    for _ in range(4):
        b = build_task(s, used)
        if b: used.add(b["id"]); items.append(b)
    random.shuffle(items)
    return items
